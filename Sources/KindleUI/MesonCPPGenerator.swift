import Foundation

/// Emits a complete, cross-compilable Meson + GTK+-2.0 C++17 project (`meson.build`, `meson.options`, `src/main.cpp`)
/// matching the KindleModding SDK (`koxtoolchain` + `kindle-sdk`) specification.
public struct MesonCPPGenerator {
    public static func writeMesonProject(
        executableName: String,
        tree: RenderNode,
        config: KindleWindowConfig,
        outputDirectory: String
    ) throws {
        let fm = FileManager.default
        let srcDir = (outputDirectory as NSString).appendingPathComponent("src")
        let includeDir = (srcDir as NSString).appendingPathComponent("include")

        try fm.createDirectory(atPath: includeDir, withIntermediateDirectories: true)

        let mesonOptionsPath = (outputDirectory as NSString).appendingPathComponent("meson.options")
        let mesonBuildPath = (outputDirectory as NSString).appendingPathComponent("meson.build")
        let headerPath = (includeDir as NSString).appendingPathComponent("kindle_ui.hpp")
        let mainCppPath = (srcDir as NSString).appendingPathComponent("main.cpp")

        let mesonOptions = """
        option('kindle_root_dir', type : 'string', value: '', description: 'The path to the Kindle\\'s mounted rootfs (for linking libraries)')
        """

        let mesonBuild = """
        project('\(executableName)', 'cpp', version: 'v1.0.0', default_options: ['cpp_std=c++17'], meson_version: '>=1.1')

        # Define dependencies we want
        gtk_dep = dependency('gtk+-2.0')

        ###
        # Project definition (Generated by KindleUI / kindle-swift)
        ###
        sources = files(
            './src/main.cpp'
        )

        include_dirs = include_directories(
            './src/include/'
        )

        executable(
            '\(executableName)',
            sources,
            include_directories: include_dirs,
            dependencies: [gtk_dep],
            cpp_args: '-static-libstdc++',
            link_args: '-static-libstdc++'
        )
        """

        let headerContent = """
        #pragma once
        #include <gtk-2.0/gtk/gtk.h>
        #include <string>
        #include <functional>
        #include <vector>

        namespace kindleui {

        inline void apply_font(GtkWidget* widget, const char* font_desc_str) {
            if (!widget || !font_desc_str) return;
            PangoFontDescription* desc = pango_font_description_from_string(font_desc_str);
            if (desc) {
                gtk_widget_modify_font(widget, desc);
                pango_font_description_free(desc);
            }
        }

        inline void apply_gray_bg(GtkWidget* widget, guint8 gray) {
            if (!widget) return;
            guint16 c16 = (static_cast<guint16>(gray) << 8) | gray;
            GdkColor color = { 0, c16, c16, c16 };
            gtk_widget_modify_bg(widget, GTK_STATE_NORMAL, &color);
        }

        inline void apply_gray_fg(GtkWidget* widget, guint8 gray) {
            if (!widget) return;
            guint16 c16 = (static_cast<guint16>(gray) << 8) | gray;
            GdkColor color = { 0, c16, c16, c16 };
            gtk_widget_modify_fg(widget, GTK_STATE_NORMAL, &color);
        }

        inline GtkWidget* wrap_padding(GtkWidget* child, guint top, guint bottom, guint left, guint right) {
            GtkWidget* align = gtk_alignment_new(0.0f, 0.0f, 1.0f, 1.0f);
            gtk_alignment_set_padding(GTK_ALIGNMENT(align), top, bottom, left, right);
            gtk_container_add(GTK_CONTAINER(align), child);
            return align;
        }

        } // namespace kindleui
        """

        var counter = 0
        let builderLines = emitNodeCPP(node: tree, parentVar: nil, counter: &counter, indent: "  ")
        let rootVar = "w_\(counter)"

        let mainCpp = """
        #include <gtk-2.0/gtk/gtk.h>
        #include "kindle_ui.hpp"

        int main(int argc, char* argv[]) {
          GtkWidget *window;

          gtk_init(&argc, &argv);

          window = gtk_window_new(GTK_WINDOW_TOPLEVEL);
          gtk_window_set_title(GTK_WINDOW(window), "\(escapeCPP(config.awesomeWindowTitle))");
          gtk_window_set_default_size(GTK_WINDOW(window), \(config.width), \(config.height));
          kindleui::apply_gray_bg(window, 255);

          g_signal_connect(window, "destroy", G_CALLBACK(gtk_main_quit), NULL);

        \(builderLines.joined(separator: "\n"))
          if (\(rootVar)) {
            gtk_container_add(GTK_CONTAINER(window), \(rootVar));
          }

          gtk_widget_show_all(window);

          gtk_main();

          return 0;
        }
        """

        try mesonOptions.write(toFile: mesonOptionsPath, atomically: true, encoding: .utf8)
        try mesonBuild.write(toFile: mesonBuildPath, atomically: true, encoding: .utf8)
        try headerContent.write(toFile: headerPath, atomically: true, encoding: .utf8)
        try mainCpp.write(toFile: mainCppPath, atomically: true, encoding: .utf8)
    }

    private static func emitNodeCPP(
        node: RenderNode,
        parentVar: String?,
        counter: inout Int,
        indent: String
    ) -> [String] {
        var lines: [String] = []

        switch node {
        case .empty:
            counter += 1
            let myVar = "w_\(counter)"
            lines.append("\(indent)GtkWidget* \(myVar) = gtk_vbox_new(FALSE, 0);")
            return lines

        case .group(let children):
            var childVars: [(String, Bool, Bool)] = []
            for child in children {
                lines.append(contentsOf: emitNodeCPP(node: child, parentVar: nil, counter: &counter, indent: indent))
                let cVar = "w_\(counter)"
                let (exp, fill) = expansion(for: child)
                childVars.append((cVar, exp, fill))
            }
            counter += 1
            let myVar = "w_\(counter)"
            lines.append("\(indent)GtkWidget* \(myVar) = gtk_vbox_new(FALSE, 4);")
            for (cVar, exp, fill) in childVars {
                lines.append("\(indent)gtk_box_pack_start(GTK_BOX(\(myVar)), \(cVar), \(exp ? "TRUE" : "FALSE"), \(fill ? "TRUE" : "FALSE"), 0);")
            }
            return lines

        case .vstack(_, let spacing, let children, let style):
            var childVars: [(String, Bool, Bool)] = []
            for child in children {
                lines.append(contentsOf: emitNodeCPP(node: child, parentVar: nil, counter: &counter, indent: indent))
                let cVar = "w_\(counter)"
                let (exp, fill) = expansion(for: child)
                childVars.append((cVar, exp, fill))
            }
            counter += 1
            let myVar = "w_\(counter)"
            lines.append("\(indent)GtkWidget* \(myVar) = gtk_vbox_new(FALSE, \(spacing));")
            for (cVar, exp, fill) in childVars {
                lines.append("\(indent)gtk_box_pack_start(GTK_BOX(\(myVar)), \(cVar), \(exp ? "TRUE" : "FALSE"), \(fill ? "TRUE" : "FALSE"), 0);")
            }
            lines.append(contentsOf: applyStyleCPP(style: style, widgetVar: myVar, indent: indent))
            return lines

        case .hstack(_, let spacing, let children, let style):
            var childVars: [(String, Bool, Bool)] = []
            for child in children {
                lines.append(contentsOf: emitNodeCPP(node: child, parentVar: nil, counter: &counter, indent: indent))
                let cVar = "w_\(counter)"
                let (exp, fill) = expansion(for: child)
                childVars.append((cVar, exp, fill))
            }
            counter += 1
            let myVar = "w_\(counter)"
            lines.append("\(indent)GtkWidget* \(myVar) = gtk_hbox_new(FALSE, \(spacing));")
            for (cVar, exp, fill) in childVars {
                lines.append("\(indent)gtk_box_pack_start(GTK_BOX(\(myVar)), \(cVar), \(exp ? "TRUE" : "FALSE"), \(fill ? "TRUE" : "FALSE"), 0);")
            }
            lines.append(contentsOf: applyStyleCPP(style: style, widgetVar: myVar, indent: indent))
            return lines

        case .zstack(_, let children, let style):
            var childVars: [String] = []
            for child in children {
                lines.append(contentsOf: emitNodeCPP(node: child, parentVar: nil, counter: &counter, indent: indent))
                childVars.append("w_\(counter)")
            }
            counter += 1
            let myVar = "w_\(counter)"
            lines.append("\(indent)GtkWidget* \(myVar) = gtk_vbox_new(FALSE, 0);")
            for cVar in childVars {
                lines.append("\(indent)gtk_box_pack_start(GTK_BOX(\(myVar)), \(cVar), TRUE, TRUE, 0);")
            }
            lines.append(contentsOf: applyStyleCPP(style: style, widgetVar: myVar, indent: indent))
            return lines

        case .scrollView(_, let child, let style):
            lines.append(contentsOf: emitNodeCPP(node: child, parentVar: nil, counter: &counter, indent: indent))
            let childVar = "w_\(counter)"
            counter += 1
            let myVar = "w_\(counter)"
            lines.append("\(indent)GtkWidget* \(myVar) = gtk_scrolled_window_new(NULL, NULL);")
            lines.append("\(indent)gtk_scrolled_window_set_policy(GTK_SCROLLED_WINDOW(\(myVar)), GTK_POLICY_AUTOMATIC, GTK_POLICY_AUTOMATIC);")
            lines.append("\(indent)gtk_scrolled_window_add_with_viewport(GTK_SCROLLED_WINDOW(\(myVar)), \(childVar));")
            lines.append(contentsOf: applyStyleCPP(style: style, widgetVar: myVar, indent: indent))
            return lines

        case .card(let title, let child, let style):
            lines.append(contentsOf: emitNodeCPP(node: child, parentVar: nil, counter: &counter, indent: indent))
            let childVar = "w_\(counter)"
            counter += 1
            let myVar = "w_\(counter)"
            if let title = title {
                lines.append("\(indent)GtkWidget* \(myVar) = gtk_frame_new(\"\(escapeCPP(title))\");")
            } else {
                lines.append("\(indent)GtkWidget* \(myVar) = gtk_frame_new(NULL);")
            }
            lines.append("\(indent)gtk_frame_set_shadow_type(GTK_FRAME(\(myVar)), GTK_SHADOW_ETCHED_IN);")
            lines.append("\(indent)gtk_container_add(GTK_CONTAINER(\(myVar)), kindleui::wrap_padding(\(childVar), 8, 8, 10, 10));")
            lines.append(contentsOf: applyStyleCPP(style: style, widgetVar: myVar, indent: indent))
            return lines

        case .text(let content, let wrap, let alignment, let style):
            counter += 1
            let myVar = "w_\(counter)"
            lines.append("\(indent)GtkWidget* \(myVar) = gtk_label_new(\"\(escapeCPP(content))\");")
            lines.append("\(indent)gtk_label_set_line_wrap(GTK_LABEL(\(myVar)), \(wrap ? "TRUE" : "FALSE"));")
            lines.append("\(indent)gtk_misc_set_alignment(GTK_MISC(\(myVar)), \(alignment.gtkAlign)f, 0.5f);")
            lines.append(contentsOf: applyStyleCPP(style: style, widgetVar: myVar, indent: indent))
            return lines

        case .button(let label, _, _, let style):
            counter += 1
            let myVar = "w_\(counter)"
            lines.append("\(indent)GtkWidget* \(myVar) = gtk_button_new_with_label(\"\(escapeCPP(label))\");")
            lines.append(contentsOf: applyStyleCPP(style: style, widgetVar: myVar, indent: indent))
            return lines

        case .toggle(let label, let isOn, _, let style):
            counter += 1
            let myVar = "w_\(counter)"
            lines.append("\(indent)GtkWidget* \(myVar) = gtk_check_button_new_with_label(\"\(escapeCPP(label))\");")
            lines.append("\(indent)gtk_toggle_button_set_active(GTK_TOGGLE_BUTTON(\(myVar)), \(isOn ? "TRUE" : "FALSE"));")
            lines.append(contentsOf: applyStyleCPP(style: style, widgetVar: myVar, indent: indent))
            return lines

        case .textField(let placeholder, let text, _, let style):
            counter += 1
            let myVar = "w_\(counter)"
            let initial = text.isEmpty ? placeholder : text
            lines.append("\(indent)GtkWidget* \(myVar) = gtk_entry_new();")
            lines.append("\(indent)gtk_entry_set_text(GTK_ENTRY(\(myVar)), \"\(escapeCPP(initial))\");")
            lines.append(contentsOf: applyStyleCPP(style: style, widgetVar: myVar, indent: indent))
            return lines

        case .slider(let value, let range, let step, _, let style):
            counter += 1
            let myVar = "w_\(counter)"
            lines.append("\(indent)GtkWidget* \(myVar) = gtk_hscale_new_with_range(\(range.lowerBound), \(range.upperBound), \(step));")
            lines.append("\(indent)gtk_range_set_value(GTK_RANGE(\(myVar)), \(value));")
            lines.append(contentsOf: applyStyleCPP(style: style, widgetVar: myVar, indent: indent))
            return lines

        case .progressBar(let fraction, let text, let style):
            counter += 1
            let myVar = "w_\(counter)"
            lines.append("\(indent)GtkWidget* \(myVar) = gtk_progress_bar_new();")
            lines.append("\(indent)gtk_progress_bar_set_fraction(GTK_PROGRESS_BAR(\(myVar)), \(fraction));")
            if let text = text {
                lines.append("\(indent)gtk_progress_bar_set_text(GTK_PROGRESS_BAR(\(myVar)), \"\(escapeCPP(text))\");")
            }
            lines.append(contentsOf: applyStyleCPP(style: style, widgetVar: myVar, indent: indent))
            return lines

        case .divider(let vertical, let style):
            counter += 1
            let myVar = "w_\(counter)"
            lines.append("\(indent)GtkWidget* \(myVar) = \(vertical ? "gtk_vseparator_new()" : "gtk_hseparator_new()");")
            lines.append(contentsOf: applyStyleCPP(style: style, widgetVar: myVar, indent: indent))
            return lines

        case .spacer(let minLen, let style):
            counter += 1
            let myVar = "w_\(counter)"
            lines.append("\(indent)GtkWidget* \(myVar) = gtk_vbox_new(FALSE, 0);")
            if let minLen = minLen {
                lines.append("\(indent)gtk_widget_set_size_request(\(myVar), \(minLen), \(minLen));")
            }
            lines.append(contentsOf: applyStyleCPP(style: style, widgetVar: myVar, indent: indent))
            return lines

        case .image(let path, _, let style):
            counter += 1
            let myVar = "w_\(counter)"
            lines.append("\(indent)GtkWidget* \(myVar) = gtk_image_new_from_file(\"\(escapeCPP(path))\");")
            lines.append(contentsOf: applyStyleCPP(style: style, widgetVar: myVar, indent: indent))
            return lines
        }
    }

    private static func applyStyleCPP(style: ViewStyle, widgetVar: String, indent: String) -> [String] {
        var lines: [String] = []
        if let font = style.font {
            lines.append("\(indent)kindleui::apply_font(\(widgetVar), \"\(escapeCPP(font.pangoDescription))\");")
        }
        if let fg = style.foregroundColor {
            lines.append("\(indent)kindleui::apply_gray_fg(\(widgetVar), \(fg.grayLevel));")
        }
        if let bg = style.backgroundColor {
            lines.append("\(indent)kindleui::apply_gray_bg(\(widgetVar), \(bg.grayLevel));")
        }
        if let w = style.width, let h = style.height {
            lines.append("\(indent)gtk_widget_set_size_request(\(widgetVar), \(w), \(h));")
        } else if let w = style.width {
            lines.append("\(indent)gtk_widget_set_size_request(\(widgetVar), \(w), -1);")
        } else if let h = style.height {
            lines.append("\(indent)gtk_widget_set_size_request(\(widgetVar), -1, \(h));")
        }
        if let p = style.padding {
            lines.append("\(indent)\(widgetVar) = kindleui::wrap_padding(\(widgetVar), \(p.top), \(p.bottom), \(p.leading), \(p.trailing));")
        }
        return lines
    }

    private static func expansion(for node: RenderNode) -> (Bool, Bool) {
        switch node {
        case .spacer:
            return (true, true)
        case .scrollView(_, _, let s),
             .vstack(_, _, _, let s),
             .hstack(_, _, _, let s),
             .zstack(_, _, let s),
             .card(_, _, let s),
             .text(_, _, _, let s),
             .button(_, _, _, let s),
             .toggle(_, _, _, let s),
             .textField(_, _, _, let s),
             .slider(_, _, _, _, let s),
             .progressBar(_, _, let s),
             .divider(_, let s),
             .image(_, _, let s):
            return (s.expand, s.fill)
        case .empty, .group:
            return (false, true)
        }
    }

    private static func escapeCPP(_ str: String) -> String {
        str
            .replacingOccurrences(of: "\\", with: "\\\\")
            .replacingOccurrences(of: "\"", with: "\\\"")
            .replacingOccurrences(of: "\n", with: "\\n")
    }
}
